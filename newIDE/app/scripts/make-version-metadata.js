/**
 * Launch this script to re-generate VersionMetadata.js and VersionMetadata.json,
 * used by the IDE and build scripts to know about the current version number.
 *
 * The version is read from `newIDE/electron-app/app/package.json`. It must
 * always be the source of truth and the only place to update when the version
 * is changed.
 */
const fs = require('fs');
var shell = require('shelljs');

const electronAppPackageJson = require('../../electron-app/app/package.json');
const version = electronAppPackageJson.version;
const jsOutputFile = '../src/Version/VersionMetadata.js';
const jsonOutputFile = '../src/Version/VersionMetadata.json';
const gitHashShellString = shell.exec(`git rev-parse "HEAD"`, {
  silent: true,
});

let gitHash = gitHashShellString.stdout.trim();
if (gitHashShellString.stderr || gitHashShellString.code) {
  shell.echo(`⚠️ Can't find the hash or branch of the associated commit.`);
  gitHash = 'unknown-hash';
}

const writeTextFile = (filePath, content) => {
  return new Promise((resolve, reject) => {
    fs.writeFile(filePath, content, err => {
      if (err) return reject(err);

      resolve();
    });
  });
};

const writeVersionMetadataFiles = versionMetadata => {
  const formattedJson = JSON.stringify(versionMetadata, null, 2);
  const jsContent = [
    `// @flow`,
    `// This file is generated by make-version-metadata.js script`,
    `// Don't import this file directly, prefer to use newIDE/app/src/Version/index.js instead.`,
    `// prettier-ignore`,
    `const versionMetadata: {|`,
    `  version: string,`,
    `  gitHash: string,`,
    `  versionWithHash: string,`,
    `|} = ${formattedJson};`,
    ``,
    `export default versionMetadata;`,
    ``,
  ].join('\n');
  const jsonContent = `${formattedJson}\n`;

  return Promise.all([
    writeTextFile(jsOutputFile, jsContent),
    writeTextFile(jsonOutputFile, jsonContent),
  ]);
};

writeVersionMetadataFiles({
  version,
  gitHash,
  versionWithHash: [version, gitHash].join('-'),
}).then(
  () =>
    console.info(
      '✅ src/Version/VersionMetadata.js and src/Version/VersionMetadata.json properly generated.'
    ),
  err =>
    console.error(
      '❌ Error while generating src/Version/VersionMetadata.js / src/Version/VersionMetadata.json',
      err
    )
);
