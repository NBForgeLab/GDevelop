/**
 * Launch this script to re-generate VersionMetadata.ts and VersionMetadata.json,
 * used by the IDE and build scripts to know about the current version number.
 *
 * The version is read from `newIDE/electron-app/app/package.json`. It must
 * always be the source of truth and the only place to update when the version
 * is changed.
 */
const fs = require('fs');
const path = require('path');
var shell = require('shelljs');

const electronAppPackageJson = require('../../electron-app/app/package.json');
const version = electronAppPackageJson.version;
const versionDir = path.resolve(__dirname, '../src/Version');
const legacyJsOutputFile = path.join(versionDir, 'VersionMetadata.js');
const tsOutputFile = path.join(versionDir, 'VersionMetadata.ts');
const jsonOutputFile = path.join(versionDir, 'VersionMetadata.json');
const gitHashShellString = shell.exec(`git rev-parse "HEAD"`, {
  silent: true,
});

let gitHash = gitHashShellString.stdout.trim();
if (gitHashShellString.stderr || gitHashShellString.code) {
  shell.echo(`⚠️ Can't find the hash or branch of the associated commit.`);
  gitHash = 'unknown-hash';
}

/**
 * @param {string} filePath
 * @param {string} content
 * @returns {Promise<void>}
 */
const writeTextFile = (filePath, content) => {
  return new Promise((resolve, reject) => {
    fs.writeFile(filePath, content, err => {
      if (err) return reject(err);

      resolve();
    });
  });
};

/**
 * @param {string} filePath
 * @returns {Promise<void>}
 */
const removeFileIfExists = filePath => {
  return new Promise((resolve, reject) => {
    if (!fs.existsSync(filePath)) return resolve();
    fs.unlink(filePath, err => {
      if (err && err.code !== 'ENOENT') return reject(err);
      resolve();
    });
  });
};

/**
 * @param {{ version: string, gitHash: string, versionWithHash: string }} versionMetadata
 */
const writeVersionMetadataFiles = versionMetadata => {
  const formattedJson = JSON.stringify(versionMetadata, null, 2);
  const tsContent = [
    `// This file is generated by make-version-metadata.js script`,
    `// Don't import this file directly, prefer to use newIDE/app/src/Version/index.ts instead.`,
    `// prettier-ignore`,
    `const versionMetadata: {`,
    `  readonly version: string;`,
    `  readonly gitHash: string;`,
    `  readonly versionWithHash: string;`,
    `} = ${formattedJson};`,
    ``,
    `export default versionMetadata;`,
    ``,
  ].join('\n');
  const jsonContent = `${formattedJson}\n`;

  return Promise.all([
    removeFileIfExists(legacyJsOutputFile),
    writeTextFile(tsOutputFile, tsContent),
    writeTextFile(jsonOutputFile, jsonContent),
  ]);
};

writeVersionMetadataFiles({
  version,
  gitHash,
  versionWithHash: [version, gitHash].join('-'),
}).then(
  () =>
    console.info(
      '✅ src/Version/VersionMetadata.ts and src/Version/VersionMetadata.json properly generated.'
    ),
  err => {
    console.error(
      '❌ Error while generating src/Version/VersionMetadata.ts / VersionMetadata.json',
      err
    );
    process.exitCode = 1;
  }
);
