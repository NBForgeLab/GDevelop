// @ts-check
const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '../../..');
const typesDtsPath = path.join(rootDir, 'GDevelop.js', 'types.d.ts');
const flowTypesDir = path.join(rootDir, 'GDevelop.js', 'types');
const targetPath = path.join(__dirname, '../src/types/gd-globals.d.ts');

if (!fs.existsSync(typesDtsPath)) {
  console.error('Cannot find GDevelop.js/types.d.ts at', typesDtsPath);
  process.exit(1);
}

const typesDts = fs.readFileSync(typesDtsPath, 'utf8');

/**
 * ES5-compatible regex match iterator
 * @param {string} str
 * @param {RegExp} regex
 * @returns {RegExpExecArray[]}
 */
function findAllMatches(str, regex) {
  const matches = [];
  let m;
  while ((m = regex.exec(str)) !== null) {
    matches.push(m);
  }
  return matches;
}

// Extract classes, enums, types from types.d.ts
const tsClasses = new Set(
  findAllMatches(typesDts, /export class (\w+)/g).map(function(m) {
    return m[1];
  })
);
const tsEnums = new Set(
  findAllMatches(typesDts, /export enum (\w+)/g).map(function(m) {
    return m[1];
  })
);
const tsTypes = new Set(
  findAllMatches(typesDts, /export type (\w+)/g).map(function(m) {
    return m[1];
  })
);

// Collect Flow names
const flowClasses = new Set();
const flowEnumsOrTypes = new Set();
if (fs.existsSync(flowTypesDir)) {
  const files = fs.readdirSync(flowTypesDir);
  for (let i = 0; i < files.length; i++) {
    const file = files[i];
    const content = fs.readFileSync(path.join(flowTypesDir, file), 'utf8');
    const classMatches = findAllMatches(content, /declare class (\w+)/g);
    for (let j = 0; j < classMatches.length; j++) {
      flowClasses.add(classMatches[j][1]);
    }
    const typeMatches = findAllMatches(
      content,
      /(?:declare type|type) (\w+)/g
    );
    for (let k = 0; k < typeMatches.length; k++) {
      flowEnumsOrTypes.add(typeMatches[k][1]);
    }
  }
}

// Generate alias mappings
const lines = [];
lines.push(
  '/**',
  ' * GDevelop.js C++ WebAssembly Ambient Type Bridge',
  ' * Maps unnamespaced gd* Flow type identifiers to GDevelop.js/types.d.ts namespaced classes.',
  ' * Enables zero-code-change type resolution for migrated TypeScript files in newIDE/app.',
  ' * Automatically generated by newIDE/app/scripts/generate-gd-globals.js',
  ' */',
  '',
  '/// <reference path="../../../../GDevelop.js/types.d.ts" />',
  '',
  'declare global {',
  '  // Type bridge for Flow compatibility',
  '  type libGDevelop = typeof gd;',
  '',
  '  // Ad-hoc Flow compatibility types',
  '  type gdSerializable = any;',
  '  type gdEmscriptenObject = {',
  '    ptr: number;',
  '    delete(): void;',
  '  };'
);

lines.push('', '  // Core C++ Class Aliases');
// Add all classes from types.d.ts
const sortedClasses = Array.from(tsClasses).sort();
for (let i = 0; i < sortedClasses.length; i++) {
  const cls = sortedClasses[i];
  if (cls === 'gdObject') {
    lines.push('  type gdObject = gd.gdObject;');
  } else {
    lines.push('  type gd' + cls + ' = gd.' + cls + ';');
  }
}

// Ensure special Flow aliases
if (!tsClasses.has('jsExporter')) {
  lines.push('  type gdjsExporter = gd.Exporter;');
}

// Check any remaining Flow classes not yet covered
const sortedFlowClasses = Array.from(flowClasses).sort();
for (let i = 0; i < sortedFlowClasses.length; i++) {
  const flowClass = sortedFlowClasses[i];
  if (flowClass.indexOf('gd') === 0) {
    const stripped = flowClass.slice(2);
    if (tsClasses.has(stripped)) continue;
    if (flowClass === 'gdObject' || flowClass === 'gdjsExporter') continue;
    console.warn('Unmapped Flow class: ' + flowClass);
  }
}

lines.push('', '  // Enums');
const sortedEnums = Array.from(tsEnums).sort();
for (let i = 0; i < sortedEnums.length; i++) {
  const enumName = sortedEnums[i];
  lines.push('  type ' + enumName + ' = gd.' + enumName + ';');
}

lines.push('', '  // Additional Exported Types');
const sortedTypes = Array.from(tsTypes).sort();
for (let i = 0; i < sortedTypes.length; i++) {
  const typeName = sortedTypes[i];
  lines.push('  type gd' + typeName + ' = gd.' + typeName + ';');
  lines.push('  type ' + typeName + ' = gd.' + typeName + ';');
}

lines.push('}', '', 'export {};', '');

// Ensure destination dir exists
fs.mkdirSync(path.dirname(targetPath), { recursive: true });
fs.writeFileSync(targetPath, lines.join('\n'), 'utf8');

console.log('Generated ' + targetPath + ' with:');
console.log('- ' + tsClasses.size + ' class aliases');
console.log('- ' + tsEnums.size + ' enum aliases');
console.log('- ' + tsTypes.size + ' type aliases');
